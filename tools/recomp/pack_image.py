#!/usr/bin/env python3
"""Write what the runtime needs to load the original executable into game memory.

  image.bin      the bound image from its first segment (0x1000) to the end of __LINKEDIT, zero fill included
  image_meta.c   constants and tables: image base and size, the import names by slot, every data word bound to an
                 import (so the runtime can point it at the real object), the static constructors, main(), the
                 Objective-C sections, and the function names for crash reports

  py -3 tools/recomp/pack_image.py --exe NovaHD --out build/runner
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from capstone import CS_ARCH_ARM, CS_MODE_ARM, Cs

sys.path.insert(0, str(Path(__file__).parent))
from lift import entries  # noqa: E402
from macho import IMPORT_STUB_BASE, Image  # noqa: E402

OBJC_SECTIONS = ["__objc_classlist", "__objc_catlist", "__objc_selrefs", "__objc_classrefs", "__objc_superrefs",
                 "__objc_protolist", "__cfstring"]


def find_main(image: Image) -> int:
    """start (crt1) ends with `bl main; b exit`: the first BL after the entry point."""
    md = Cs(CS_ARCH_ARM, CS_MODE_ARM)
    for i in md.disasm(bytes(image.memory[image.entry:image.entry + 0x80]), image.entry):
        if i.mnemonic == "bl":
            return int(i.op_str.lstrip("#"), 16)
    raise ValueError("no call to main in start")


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    image = Image(args.exe)
    args.out.mkdir(parents=True, exist_ok=True)
    base = min(s[0] for s in image.segments)
    (args.out / "image.bin").write_bytes(bytes(image.memory[base:]))

    slots = {name: k for k, name in enumerate(image.imports)}
    binds = {}
    for addr, name in list(image.pointer_imports.items()) + list(image.bound.items()):
        if name not in slots:
            continue  # bound to a weak definition inside the image: already final
        word = image.u32(addr)
        binds[addr] = (slots[name], (word - image.imports[name]) & 0xFFFFFFFF)
    init = image.section("__DATA", "__mod_init_func")
    inits = [image.u32(init.addr + 4 * k) for k in range(init.size // 4)] if init else []
    objc = []
    for name in OBJC_SECTIONS:
        s = image.section("__DATA", name)
        objc.append((s.addr, s.size) if s else (0, 0))
    ents = entries(image)
    funcs = sorted(ents.items())

    out = ["/* Generated by tools/recomp/pack_image.py. */", '#include "rt.h"', "",
           f"const uint32_t rt_image_base = {base:#x}u;",
           f"const uint32_t rt_image_size = {image.size - base:#x}u;",
           f"const uint32_t rt_import_stub_base = {IMPORT_STUB_BASE:#x}u;",
           f"const uint32_t rt_init_funcs[] = {{ {', '.join(f'{a:#x}u' for a in inits) or '0'} }};",
           f"const uint32_t rt_init_func_count = {len(inits)};",
           f"const uint32_t rt_main = {find_main(image):#x}u;",
           f"const char *const rt_import_names[] = {{ {', '.join(c_str(n) for n in image.imports)} }};",
           f"const uint32_t rt_import_count = {len(image.imports)};",
           "const rt_bind rt_binds[] = {"]
    out += [f"  {{{a:#x}u, {s}u, {ad:#x}u}}," for a, (s, ad) in sorted(binds.items())]
    out += ["};", f"const uint32_t rt_bind_count = {len(binds)};",
            "const uint32_t rt_objc_sections[][2] = { " + ", ".join(f"{{{a:#x}u, {z:#x}u}}" for a, z in objc) + " };",
            "const uint32_t rt_func_addrs[] = {"]
    out += ["  " + ", ".join(f"{a:#x}u" for a, _ in funcs[k:k + 12]) + "," for k in range(0, len(funcs), 12)]
    out += ["};", f"const uint32_t rt_func_count = {len(funcs)};", "const char *const rt_func_names[] = {"]
    out += [f"  {c_str(f.name)}," for _, f in funcs]
    out += ["};", ""]
    (args.out / "image_meta.c").write_text("\n".join(out), encoding="utf-8")
    print(f"image {base:#x}+{image.size - base:#x}, {len(image.imports)} imports, {len(binds)} bound words, "
          f"{len(inits)} constructors, main {find_main(image):#x}, {len(funcs)} functions")


if __name__ == "__main__":
    main()
